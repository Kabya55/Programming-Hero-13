// Checking Array Membership with ‘includes’
// Instructions:
// Create an array of books containing different book.
// Use the includes method to check if the array contains a javascript book.
// Print a message to the console indicating whether the element is present in the array or not.

const book = ["HTML", "CSS", "JavaScript", "Python", "React"];
if (book.includes("JavaScript")) {
  console.log("JavaScript is found in the book array.");
} else {
  console.log("JavaScript is not found in the book array.");
}
