const result = 33;

if (result >= 80) {
  console.log("You got an A+(5).");
} else if (result >= 70) {
  console.log("You got an A(4).");
} else if (result >= 60) {
  console.log("You got an A-(3.5).");
} else if (result >= 50) {
  console.log("You got an B(3).");
} else if (result >= 40) {
  console.log("You got an C(2).");
} else if (result >= 33) {
  console.log("You got an D(1).");
} else {
  console.log("You got an F(0).");
}
