//  Find all the odd numbers from 61 to 100.

let i = 61;
while (i <= 100) {
  if (i % 2 !== 0) {
    console.log(i);
  }
  i++;
}

let k = 61;
while (k <= 100) {
  if (k % 2 === 1) {
    console.log(k);
  }
  k++;
}

let t = 61;
while (t <= 100) {
  console.log(t);
  t += 2;
}

